namespace FSharp.Wasm.Design

open FSharp.Wasm.Ui
open FSharp.Wasm.Data

/// What leaves the library: the stylesheet of custom properties a page links (`--fw-*`), and the same values as JSON for whatever draws them (the brand page, a canvas theme).
module Export =
    let private hexOf (c: Color) : string =
        match c with
        | Hex h -> h
        | other -> (match Color.toHex other with Some h -> h | None -> "#000000")

    let private prop (name: string) (v: Value) : Decl = Style.customProperty ("fw-" + name) v
    let private colour (name: string) (c: Color) : Decl = prop name (VColor(Hex(hexOf c)))
    let private rem (px: int) : Value = VLength(Rem(float px / 16.0))

    let private ramps : Decl list =
        Palette.all |> List.collect (fun r -> Palette.steps |> List.map (fun s -> colour (r.Name + "-" + string s) (Palette.colour r s)))

    let private roles (t: Tokens) : Decl list =
        let rgb = match Color.toRgb t.Primary with Some(r, g, b) -> sprintf "%d, %d, %d" r g b | None -> "0, 0, 0"
        (Tokens.roles |> List.map (fun (name, get) -> colour name (get t))) @ [ prop "primary-rgb" (VText rgb) ]

    /// The same in every theme.
    let private scale : Decl list =
        (Scale.space |> List.map (fun n -> prop ("space-" + string n) (VLength(Px(float (4 * n))))))
        @ (Scale.radius |> List.map (fun (name, px) -> prop ("radius-" + name) (VLength(Px(float px)))))
        @ [ prop "radius" (VLength(Px 8.0)) ]
        @ (Scale.size |> List.map (fun (name, px) -> prop ("size-" + name) (rem px)))
        @ (Scale.weight |> List.map (fun (name, w) -> prop ("weight-" + name) (VNumber(float w))))
        @ (Scale.leading |> List.map (fun (name, l) -> prop ("leading-" + name) (VNumber l)))
        @ (Scale.duration |> List.map (fun (name, ms) -> prop ("duration-" + name) (VText(string ms + "ms"))))
        @ [ prop "ease-out" (VText Scale.easeOut)
            prop "ease-in" (VText Scale.easeIn)
            prop "font" (VText Scale.sans)
            prop "mono" (VText Scale.mono)
            prop "bar-height" (VLength(Rem Scale.barHeight)) ]

    let private scheme (name: string) : Decl = Style.decl "color-scheme" (VKeyword name)

    /// The stylesheet: light by default, dark when the system asks for it, and when the page says `data-theme="dark"` (and `data-theme="light"` keeps a page light on a dark system).
    /// CSS has no way to write the dark values once for both, so they are rendered twice from the same tokens.
    let css : string =
        let dark = scheme "dark" :: prop "shadow" (VKeyword "none") :: roles Tokens.dark
        Style.render Web
            [ Comment "Generated by FSharp.Wasm.Design (fsharp-wasm-core): do not edit; change the tokens and run `dotnet run --project tools/design`."
              Style.rule [ ":root" ] ([ scheme "light"; prop "shadow" (VText Scale.shadow) ] @ roles Tokens.light @ ramps @ scale)
              Media(MediaRaw "(prefers-color-scheme: dark)", [ Style.rule [ ":root:not([data-theme=\"light\"])" ] dark ])
              Style.rule [ ":root[data-theme=\"dark\"]" ] dark ]

    let private round2 (x: float) : float = System.Math.Floor(x * 100.0 + 0.5) / 100.0

    let private theme (t: Tokens) : Json = JObj(Tokens.roles |> List.map (fun (name, get) -> name, JStr(hexOf (get t))))

    /// The tokens as JSON: the ramps, both themes, the contrast every check has in each, and the scales.
    let json : Json =
        let ratioOf (t: Tokens) (c: Tokens.Check) = match Tokens.ratio t c with Some r -> JNum(round2 r) | None -> JNull
        let ints (xs: (string * int) list) = JObj(xs |> List.map (fun (n, v) -> n, JNum(float v)))
        JObj [ "ramps", JObj(Palette.all |> List.map (fun r -> r.Name, JObj(Palette.steps |> List.map (fun s -> string s, JStr(hexOf (Palette.colour r s))))))
               "light", theme Tokens.light
               "dark", theme Tokens.dark
               "checks",
               JArr(Tokens.checks |> List.map (fun c ->
                   JObj [ "fore", JStr c.Fore; "back", JStr c.Back; "minimum", JNum c.Minimum; "why", JStr c.Why
                          "light", ratioOf Tokens.light c; "dark", ratioOf Tokens.dark c ]))
               "scale",
               JObj [ "space", JArr(Scale.space |> List.map (fun n -> JNum(float (4 * n))))
                      "radius", ints Scale.radius
                      "size", ints Scale.size
                      "weight", ints Scale.weight
                      "leading", JObj(Scale.leading |> List.map (fun (n, v) -> n, JNum v))
                      "duration", ints Scale.duration
                      "easeOut", JStr Scale.easeOut
                      "easeIn", JStr Scale.easeIn
                      "sans", JStr Scale.sans
                      "mono", JStr Scale.mono ] ]
